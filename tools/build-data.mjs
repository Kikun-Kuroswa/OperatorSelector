// Builds data/operators.js from Arkpedia's public operator pages.
// Usage:  node tools/build-data.mjs
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://www.arkpedia.net";
const IMG = "https://assets.arkpedia.net/arkpedia/arkpedia-image-assets/ea3efde6773c3e3cfd3c6abd275c55f3ef632ea3";
const SKIN = "https://assets.arkpedia.net/arkpedia/arkpedia-skin-assets/792389c3bb4284ec821f0bef372c156c058335c7";

const decode = (s) => s.replace(/&#x27;/g, "'").replace(/&amp;/g, "&").replace(/&quot;/g, '"');

async function getJson(url) {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(url);
      if (!r.ok) throw new Error(r.status);
      const html = await r.text();
      const m = html.match(/<script id="__NEXT_DATA__"[^>]*>(.*?)<\/script>/s);
      return JSON.parse(m[1]).props.pageProps;
    } catch (e) {
      if (i === 3) throw new Error(`${url}: ${e.message}`);
      await new Promise((r) => setTimeout(r, 500 * (i + 1)));
    }
  }
}

async function exists(url) {
  try {
    const r = await fetch(url, { method: "HEAD" });
    return r.ok;
  } catch {
    return false;
  }
}

async function pool(items, n, fn) {
  const out = new Array(items.length);
  let i = 0;
  await Promise.all(
    Array.from({ length: n }, async () => {
      while (i < items.length) {
        const k = i++;
        out[k] = await fn(items[k], k);
      }
    })
  );
  return out;
}

const list = (await getJson(`${SITE}/operators`)).operators;
console.log(`Found ${list.length} operators`);

let done = 0;
const ops = await pool(list, 8, async (o) => {
  const p = await getJson(`${SITE}/operators/${encodeURIComponent(o.name)}`);
  const op = p.operator;
  const base = p.appearances?.find((a) => a.label === "Base") ?? p.appearances?.[0];
  const e2 = p.appearances?.find((a) => /Elite 2/i.test(a.label));
  const art = e2 ?? base;
  const enc = (path) => path; // paths from the site are already URL-encoded
  const icon = base ? IMG + enc(base.iconPath) : null;
  const full = art ? SKIN + enc(art.fullPath) : null;

  const tags = new Set((op.tags ?? []).map((t) => t.trim()).filter(Boolean));
  if (op.position) tags.add(op.position); // Melee / Ranged
  if (op.rarity === 6) tags.add("Top Operator");
  if (op.rarity === 5) tags.add("Senior Operator");

  if (++done % 50 === 0) console.log(`  ${done}/${list.length}`);
  return {
    name: decode(op.name),
    rarity: op.rarity,
    class: op.class,
    branch: op.branch,
    faction: op.faction ?? null,
    position: op.position ?? null,
    tags: [...tags],
    future: !!o.isFuture,
    icon,
    art: full,
    artLabel: art?.label ?? null,
    url: `${SITE}/operators/${encodeURIComponent(decode(o.name))}`,
  };
});

// verify images (fall back to icon-only when the full art 404s)
await pool(ops, 12, async (o) => {
  if (o.icon && !(await exists(o.icon))) o.icon = null;
  if (o.art && !(await exists(o.art))) {
    o.art = null;
    o.artLabel = null;
  }
});

ops.sort((a, b) => b.rarity - a.rarity || a.name.localeCompare(b.name));
await mkdir(join(ROOT, "data"), { recursive: true });
await writeFile(
  join(ROOT, "data", "operators.js"),
  `// Generated by tools/build-data.mjs from arkpedia.net - ${new Date().toISOString()}\nwindow.OPERATORS = ${JSON.stringify(ops)};\n`
);
console.log(`Wrote ${ops.length} operators. No icon: ${ops.filter((o) => !o.icon).length}, no art: ${ops.filter((o) => !o.art).length}`);
